import {createHash} from 'node:crypto';
import {readdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
const hash=createHash('sha256');
async function visit(directory){for(const file of (await readdir(directory,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){const name=path.join(directory,file.name);if(name==='lib/release.ts')continue;if(file.isDirectory())await visit(name);else if(file.isFile()){hash.update(name);hash.update(await readFile(name));}}}
for(const directory of ['lib','components','app','public','scripts','db','drizzle'])await visit(directory);
for(const file of ['package.json','.openai/hosting.json'])hash.update(await readFile(file));
const id=hash.digest('hex').slice(0,16);
await writeFile('lib/release.ts',`// Generated by prepare-release.mjs: each source/art update opens a fresh world.\nexport const RELEASE_ID='${id}';\n`);
console.log('Game release '+id+' · new persistent universe for this update');
