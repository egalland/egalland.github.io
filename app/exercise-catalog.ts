function normalizeExerciseName(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

const catalogByKey = new Map(EXERCISE_CATALOG.map((item) => [item.key, item]));
const catalogByName = new Map(
  EXERCISE_CATALOG.map((item) => [normalizeExerciseName(item.name), item]),
);

const aliases: Record<string, string> = {
  tractions: "pull-up",
  "tirage vertical": "lat-pulldown",
  "tirage prise neutre": "neutral-pulldown",
  "rowing assis": "cable-row",
  "rowing unilateral": "single-cable-row",
  "curl biceps": "cable-curl",
  "developpe epaules": "dumbbell-shoulder-press",
  "elevations laterales": "lateral-raise",
  "extension triceps": "cable-pushdown",
  "ecarte a la poulie": "cable-fly",
  "souleve de terre roumain": "romanian-deadlift",
  fentes: "walking-lunge",
  squat: "back-squat",
  "squat tempo": "back-squat",
  "hip thrust": "hip-thrust",
  "mollets debout": "standing-calf-raise",
  "mollets unilateraux": "single-calf-raise",
};

export function findExerciseDefinition(nameOrKey: string | null | undefined) {
  if (!nameOrKey) return undefined;
  const direct = catalogByKey.get(nameOrKey);
  if (direct) return direct;
  const normalized = normalizeExerciseName(nameOrKey);
  const alias = aliases[normalized];
  return (
    (alias ? catalogByKey.get(alias) : undefined) ??
    catalogByName.get(normalized)
  );
}

export function coerceMuscles(value: unknown): MuscleId[] {
  const parsed = Array.isArray(value)
    ? value
    : typeof value === "string"
      ? (() => {
          try {
            return JSON.parse(value) as unknown;
          } catch {
            return [];
          }
        })()
      : [];
  if (!Array.isArray(parsed)) return [];
  return parsed.filter((item): item is MuscleId =>
    MUSCLE_IDS.includes(item as MuscleId),
  );
}
