export type ExerciseDefinition = {
  key: string;
  name: string;
  category: string;
  movement: string;
  equipment: string;
  primaryMuscles: MuscleId[];
  secondaryMuscles: MuscleId[];
  defaultSets: number;
  repsMin: number;
  repsMax: number;
  restSeconds: number;
  homeCompatible: boolean;
  cue: string;
};

function exercise(
  key: string,
  name: string,
  category: string,
  movement: string,
  equipment: string,
  primaryMuscles: MuscleId[],
  secondaryMuscles: MuscleId[] = [],
  options: Partial<
    Pick<
      ExerciseDefinition,
      | "defaultSets"
      | "repsMin"
      | "repsMax"
      | "restSeconds"
      | "homeCompatible"
      | "cue"
    >
  > = {},
): ExerciseDefinition {
  return {
    key,
    name,
    category,
    movement,
    equipment,
    primaryMuscles,
    secondaryMuscles,
    defaultSets: options.defaultSets ?? 3,
    repsMin: options.repsMin ?? 8,
    repsMax: options.repsMax ?? 12,
    restSeconds: options.restSeconds ?? 90,
    homeCompatible: options.homeCompatible ?? true,
    cue:
      options.cue ??
      "Mouvement contrôlé, amplitude stable et répétitions propres.",
  };
}

